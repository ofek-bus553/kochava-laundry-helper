const chat = document.getElementById('chat');

function addMsg(html, who){
  const div = document.createElement('div');
  div.className = 'msg ' + who;
  const b = document.createElement('div');
  b.className = 'bubble';
  b.innerHTML = html;
  div.appendChild(b);
  chat.appendChild(div);
  div.scrollIntoView({behavior:'smooth', block:'end'});
  return b;
}

function botAnswer(html){
  const t = addMsg('<div class="typing"><i></i><i></i><i></i></div>', 'bot');
  setTimeout(()=>{ t.innerHTML = html; t.parentElement.scrollIntoView({behavior:'smooth', block:'end'}); }, 550);
}

function norm(s){ return (s||'').toLowerCase().replace(/["'״׳]/g,'').trim(); }

function answer(text){
  const q = norm(text);
  let best = null, bestScore = 0;
  for(const item of KB){
    let score = 0;
    for(const k of item.keys){
      const kk = norm(k);
      if(kk && q.includes(kk)) score += kk.length;
    }
    if(score > bestScore){ bestScore = score; best = item; }
  }
  botAnswer(best ? best.a : FALLBACK);
}

function ask(text){
  addMsg(text, 'user');
  answer(text);
}

function makeChips(){
  const chips = document.getElementById('chips');
  const hot = document.getElementById('hotchips');
  for(const item of KB){
    const b = document.createElement('button');
    b.className = 'chip' + (item.hot ? ' hot' : '');
    b.type = 'button';
    b.textContent = item.chip;
    b.onclick = () => ask(item.chip.replace(/^[^\s]+\s/, ''));
    (item.hot ? hot : chips).appendChild(b);
  }
}

document.getElementById('go').onclick = () => {
  const inp = document.getElementById('q');
  if(inp.value.trim()){ ask(inp.value.trim()); inp.value=''; }
};
document.getElementById('q').addEventListener('keydown', e => {
  if(e.key === 'Enter' && e.target.value.trim()){ ask(e.target.value.trim()); e.target.value=''; }
});

